"""Export the same schemas served at /openapi.json, without contacting providers."""
import json
from pathlib import Path
from .app import create_app
from .config import REPO_ROOT
from .tools import REGISTRY


def main():
    path = Path(__file__).with_name('openapi.json')
    path.write_text(json.dumps(create_app().openapi(), indent=2, sort_keys=True) + '\n')
    print(f'Exported {path}')
    definitions = [{"name": tool.name, "description": tool.description,
                    "input_schema": tool.json_schema, "roles": sorted(tool.roles)}
                   for tool in REGISTRY.values()]
    tools_path = path.with_name('agent-tools.json')
    tools_path.write_text(json.dumps(definitions, indent=2, sort_keys=True) + '\n')
    names = ',\n  '.join(json.dumps(tool.name) for tool in REGISTRY.values())
    manifest = REPO_ROOT / 'web/app/src/api/agentTools.gen.ts'
    manifest.write_text('// Generated by python -m server.export_openapi. Do not edit.\n'
                        + 'export const TOOL_NAMES = [\n  ' + names + ',\n] as const\n')
    print(f'Exported {tools_path} and {manifest}')


if __name__ == '__main__':
    main()
