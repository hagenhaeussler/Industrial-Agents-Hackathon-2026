// Generates src/api.gen.ts from the Python API's OpenAPI schema, so the TypeScript building types
// cannot drift from the Pydantic models in building_db/source.py.
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const repo = fileURLToPath(new URL("../../..", import.meta.url));
const schema = JSON.parse(
  execFileSync("uv", ["run", "--quiet", "python", "-m", "building_api", "openapi"], { cwd: repo, encoding: "utf8" }),
);
const header = "// Generated by scripts/gen-api.mjs from the building API schema. Do not edit.\n\n";
const output = fileURLToPath(new URL("../src/api.gen.ts", import.meta.url));
writeFileSync(output, header + astToString(await openapiTS(schema)));
console.log(`wrote ${output}`);
